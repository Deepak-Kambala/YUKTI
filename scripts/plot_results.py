"""
Plot real benchmark results (runtime, objective magnitude, iterations/nodes)
from results/benchmark_results.csv. Produces PNGs under results/summaries/.
Only plots data that was actually generated by scripts/run_benchmarks.py --
no synthetic/placeholder numbers.
"""
import sys, os, csv
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

RESULTS_CSV = os.path.join(os.path.dirname(__file__), "..", "results", "benchmark_results.csv")
OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "results", "summaries")


def load_rows():
    with open(RESULTS_CSV) as f:
        return list(csv.DictReader(f))


def plot_runtime(rows):
    names = [r["instance"] for r in rows]
    times = [float(r["runtime_sec"]) for r in rows]
    colors = ["#2b8a3e" if r["status"] == "OPTIMAL" else "#c92a2a" for r in rows]
    plt.figure(figsize=(11, 5))
    plt.bar(names, times, color=colors)
    plt.ylabel("Runtime (sec, actual measured)")
    plt.title("Sovereign Optimization Engine -- Benchmark Runtime (real execution)")
    plt.xticks(rotation=60, ha="right")
    plt.tight_layout()
    plt.savefig(os.path.join(OUT_DIR, "runtime.png"), dpi=140)
    plt.close()


def plot_nodes(rows):
    milp_rows = [r for r in rows if r["problem_type"] == "MILP" and r["status"] == "OPTIMAL"]
    if not milp_rows:
        return
    names = [r["instance"] for r in milp_rows]
    nodes = [int(r["iterations_or_nodes"]) for r in milp_rows]
    plt.figure(figsize=(8, 4))
    plt.bar(names, nodes, color="#1864ab")
    plt.ylabel("B&B nodes explored (actual)")
    plt.title("MILP instances -- nodes explored")
    plt.xticks(rotation=30, ha="right")
    plt.tight_layout()
    plt.savefig(os.path.join(OUT_DIR, "bnb_nodes.png"), dpi=140)
    plt.close()


if __name__ == "__main__":
    rows = load_rows()
    os.makedirs(OUT_DIR, exist_ok=True)
    plot_runtime(rows)
    plot_nodes(rows)
    print(f"Wrote plots to {OUT_DIR}")
